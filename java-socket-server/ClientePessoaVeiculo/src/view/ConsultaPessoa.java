    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        try {
           String host = "localhost";
           int porta = 12345;

            Socket clienteSocket = new Socket(host, porta);
            System.out.println("Conexão efetuada com sucesso!");

            ObjectOutputStream out = new ObjectOutputStream(clienteSocket.getOutputStream());
            ObjectInputStream in = new ObjectInputStream(clienteSocket.getInputStream());

            int id = Integer.parseInt(txtIdPessoa.getText());
            out.writeInt(id);
            out.flush();

            Pessoa p = (Pessoa) in.readObject();
            System.out.println("Resposta: " + p.getNome());

            txtNome.setText(p.getNome());
            txtSexo.setText(p.getSexo());
            txtIdioma.setText(p.getIdioma());

            out.close();
            in.close();
            clienteSocket.close();

        } catch (IOException ex) {
            System.out.println("Erro na comunicação com o servidor: "+ex.getMessage());
        } catch (ClassNotFoundException ex) {
            System.out.println("Classe Pessoa não encontrada");
        }
    }//GEN-LAST:event_btnConsultarActionPerformed


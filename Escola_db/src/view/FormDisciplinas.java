    private void btnCadastroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastroActionPerformed
    try {
        Disciplina d = new Disciplina();
        d.setNome(txtNome.getText().trim());

        String carga = txtCargaHoraria.getText().trim();
        d.setCargaHoraria(Integer.parseInt(carga));

        Professor p = (Professor) cmbProfessores.getSelectedItem();

        if (d.getNome().isEmpty() || d.getCargaHoraria() <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Preencha o nome e uma carga horária maior que zero!"
            );
            return;
        }

        if (p == null) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Selecione um professor!"
            );
            return;
        }

        d.setProfessor(p);

        DisciplinaDAO dao = new DisciplinaDAO();
        dao.inserir(d);

        javax.swing.JOptionPane.showMessageDialog(
            this, "Disciplina cadastrada com sucesso!"
        );

        txtNome.setText("");
        txtCargaHoraria.setText("");
        cmbProfessores.setSelectedIndex(-1);

    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Digite uma carga horária válida!"
        );
    } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Erro ao cadastrar: " + ex.getMessage()
        );
    }
    }//GEN-LAST:event_btnCadastroActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        lblId.setVisible(true);
        txtId.setVisible(true);

        revalidate();
        repaint();

        if (txtId.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Digite o ID da disciplina!"
            );
            txtId.requestFocus();
            return;
        }

        try {
            int id = Integer.parseInt(txtId.getText().trim());

            DisciplinaDAO dao = new DisciplinaDAO();
            Disciplina d = dao.getDisciplina(id);

            if (d == null) {
                javax.swing.JOptionPane.showMessageDialog(
                    this, "Disciplina não encontrada!"
                );
                return;
            }

            txtNome.setText(d.getNome());

            txtCargaHoraria.setText(
                String.valueOf(d.getCargaHoraria())
            );

            cmbProfessores.setSelectedIndex(-1);

            for (int i = 0; i < cmbProfessores.getItemCount(); i++) {
                Professor p = (Professor) cmbProfessores.getItemAt(i);

                if (d.getProfessor() != null &&
                    p.getId() == d.getProfessor().getId()) {

                    cmbProfessores.setSelectedIndex(i);
                    break;
                }
            }

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Digite um ID válido!"
            );
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Erro ao consultar: " + ex.getMessage()
            );
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
    try {
        int id = Integer.parseInt(txtId.getText().trim());
        String nome = txtNome.getText().trim();
        int carga = Integer.parseInt(
            txtCargaHoraria.getText().trim()
        );

        Professor p = (Professor) cmbProfessores.getSelectedItem();

        if (nome.isEmpty() || carga <= 0 || p == null) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Preencha todos os campos corretamente!"
            );
            return;
        }

        DisciplinaDAO dao = new DisciplinaDAO();

        if (dao.getDisciplina(id) == null) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Disciplina não encontrada!"
            );
            return;
        }

        Disciplina d = new Disciplina();

        d.setId(id);
        d.setNome(nome);
        d.setCargaHoraria(carga);
        d.setProfessor(p);

        dao.editar(d);

        javax.swing.JOptionPane.showMessageDialog(
            this, "Disciplina atualizada com sucesso!"
        );

        txtId.setText("");
        txtNome.setText("");
        txtCargaHoraria.setText("");
        cmbProfessores.setSelectedIndex(-1);

        lblId.setVisible(false);
        txtId.setVisible(false);

        revalidate();
        repaint();

    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Digite um ID e uma carga horária válidos!"
        );
    } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Erro ao atualizar: " + ex.getMessage()
        );
    }
    }//GEN-LAST:event_btnAtualizarActionPerformed

